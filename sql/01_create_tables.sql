
-- AgriYield: Crop Yield Analysis and Agricultural Decision Support System
-- Phase 1: Database table creation

-- 1. Countries
CREATE TABLE countries (
    country_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    country_name VARCHAR2(100) NOT NULL,
    faostat_area_code NUMBER NOT NULL,
    CONSTRAINT pk_countries PRIMARY KEY (country_id),
    CONSTRAINT uq_country_code UNIQUE (faostat_area_code)
);

-- 2. Crops
CREATE TABLE crops (
    crop_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    crop_name VARCHAR2(150) NOT NULL,
    faostat_item_code VARCHAR2(30),
    CONSTRAINT pk_crops PRIMARY KEY (crop_id),
    CONSTRAINT uq_crop_code UNIQUE (faostat_item_code)
);

-- 3. Agricultural years
CREATE TABLE agricultural_years (
    year_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    year_value NUMBER(4) NOT NULL,
    CONSTRAINT pk_agricultural_years PRIMARY KEY (year_id),
    CONSTRAINT uq_year_value UNIQUE (year_value)
);

-- 4. Data quality flags
CREATE TABLE data_quality_flags (
    flag_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    flag_code VARCHAR2(20) NOT NULL,
    flag_description VARCHAR2(255),
    CONSTRAINT pk_data_quality_flags PRIMARY KEY (flag_id),
    CONSTRAINT uq_flag_code UNIQUE (flag_code)
);

-- 5. Crop statistics
CREATE TABLE crop_statistics (
    statistic_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    country_id NUMBER NOT NULL,
    crop_id NUMBER NOT NULL,
    year_id NUMBER NOT NULL,
    element_code NUMBER NOT NULL,
    indicator_name VARCHAR2(100) NOT NULL,
    unit VARCHAR2(50) NOT NULL,
    value NUMBER(20,6) NOT NULL,
    flag_id NUMBER,

    CONSTRAINT pk_crop_statistics PRIMARY KEY (statistic_id),

    CONSTRAINT fk_stats_country
        FOREIGN KEY (country_id)
        REFERENCES countries(country_id),

    CONSTRAINT fk_stats_crop
        FOREIGN KEY (crop_id)
        REFERENCES crops(crop_id),

    CONSTRAINT fk_stats_year
        FOREIGN KEY (year_id)
        REFERENCES agricultural_years(year_id),

    CONSTRAINT fk_stats_flag
        FOREIGN KEY (flag_id)
        REFERENCES data_quality_flags(flag_id),

    CONSTRAINT uq_crop_statistic
        UNIQUE (country_id, crop_id, year_id, element_code)
);

-- 6. Raw FAOSTAT staging table
CREATE TABLE faostat_staging (
    domain_code VARCHAR2(50),
    domain_name VARCHAR2(255),
    area_code VARCHAR2(50),
    area_name VARCHAR2(100),
    element_code VARCHAR2(50),
    element_name VARCHAR2(100),
    item_code VARCHAR2(50),
    item_name VARCHAR2(150),
    year_code VARCHAR2(20),
    year_value VARCHAR2(20),
    unit VARCHAR2(50),
    value_text VARCHAR2(100),
    flag_code VARCHAR2(20),
    flag_description VARCHAR2(255),
    note_text VARCHAR2(1000)
);
